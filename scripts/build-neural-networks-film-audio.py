#!/usr/bin/env python3
"""Concatenate the Part 02 chapter narration clips into one film soundtrack.

Each chapter occupies max(clip length, last word + HOLD) seconds; shorter clips
are padded with silence so the animation always has time to settle.
Writes public/series/neural-networks/audio/full-film.mp3 and
series/neural-networks/src/film-timing.js (chapter offsets in the film).
Run after scripts/align-neural-networks.py.
"""
import json, os, re, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUD = os.path.join(ROOT, 'public/series/neural-networks/audio')
TIMING = os.path.join(ROOT, 'series/neural-networks/src/timing-data.js')
OUT_JS = os.path.join(ROOT, 'series/neural-networks/src/film-timing.js')
HOLD = 1.2
SR = 44100


def dur(path):
    return float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path]).strip())


def main():
    words = json.loads(re.search(r'export const WORDS = (.*);', open(TIMING).read()).group(1))
    lengths = []
    with tempfile.TemporaryDirectory() as td:
        parts = []
        for i in range(5):
            src = os.path.join(AUD, f'chapter-0{i + 1}.mp3')
            L = round(max(dur(src), words[i][-1][2] + HOLD), 3)
            lengths.append(L)
            out = os.path.join(td, f'{i}.wav')
            subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', src, '-af', f'apad,atrim=0:{L}', '-ar', str(SR), '-ac', '2', out], check=True)
            parts.append(out)
        lst = os.path.join(td, 'list.txt')
        open(lst, 'w').write(''.join(f"file '{p}'\n" for p in parts))
        wav = os.path.join(td, 'full.wav')
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-f', 'concat', '-safe', '0', '-i', lst, '-c', 'copy', wav], check=True)
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', wav, '-c:a', 'libmp3lame', '-b:a', '192k', os.path.join(AUD, 'full-film.mp3')], check=True)
    offsets, acc = [], 0.0
    for L in lengths:
        offsets.append(round(acc, 3)); acc += L
    with open(OUT_JS, 'w') as f:
        f.write('// Generated by scripts/build-neural-networks-film-audio.py — chapter placement in audio/full-film.mp3.\n')
        f.write(f'export const CHAPTER_OFFSETS = {json.dumps(offsets)};\nexport const CHAPTER_LENGTHS = {json.dumps(lengths)};\nexport const FILM_DURATION = {round(acc, 3)};\n')
    print(offsets, lengths, acc)


if __name__ == '__main__':
    main()
