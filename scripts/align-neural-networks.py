#!/usr/bin/env python3
"""Forced-align the Part 02 (neural networks) narration to its script.

Produces series/neural-networks/src/timing-data.js with word-level timings
for each chapter clip. Requires: pip install pocketsphinx; ffmpeg.
Usage: python3 scripts/align-neural-networks.py
"""
import json, os, re, subprocess, tempfile, wave
import pocketsphinx
from pocketsphinx import Decoder

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPT = os.path.join(ROOT, 'docs/series-planning/02-neural-networks-and-llm-training-script.md')
AUDIO = os.path.join(ROOT, 'public/series/neural-networks/audio/chapter-0{}.mp3')
OUT = os.path.join(ROOT, 'series/neural-networks/src/timing-data.js')
MD = os.path.join(os.path.dirname(pocketsphinx.__file__), 'model', 'en-us')
EXTRA = {'backpropagation': 'B AE K P R AA P AH G EY SH AH N', 'classifier': 'K L AE S AH F AY ER',
         "layer's": 'L EY ER Z', 'llm': 'EH L EH L EH M', 'neuroevolution': 'N UH R OW EH V AH L UW SH AH N',
         'optimizer': 'AA P T AH M AY Z ER', 'perceptron': 'P ER S EH P T R AA N', 'rescale': 'R IY S K EY L'}
SPOKEN = {'1943': 'nineteen forty three', '1958': 'nineteen fifty eight'}


def chapter_texts():
    src = open(SCRIPT, encoding='utf-8').read()
    parts = re.split(r'\n## 0(\d) ', src)
    texts = {}
    for i in range(1, len(parts), 2):
        body = parts[i + 1].split('### Voice-over', 1)[1].split('\n---')[0].split('\n## ')[0]
        texts[int(parts[i])] = body.strip()
    return texts


def align(n, text):
    raw = text.replace('—', ' — ').split()
    raw = [w for w in raw if re.search(r'[A-Za-z0-9]', w)]
    toks = []  # (spoken token, raw index)
    for ri, w in enumerate(raw):
        s = SPOKEN.get(re.sub(r'[^0-9]', '', w), None) if re.search(r'\d', w) else None
        parts = s.split() if s else re.sub(r"[^a-zA-Z'\-]", '', w.replace('’', "'")).lower().strip("'").split('-')
        toks += [(p, ri) for p in parts if p]
    with tempfile.TemporaryDirectory() as td:
        wav = os.path.join(td, 'a.wav')
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', AUDIO.format(n), '-ac', '1', '-ar', '16000', wav], check=True)
        d = Decoder(hmm=os.path.join(MD, 'en-us'), dict=os.path.join(MD, 'cmudict-en-us.dict'), loglevel='FATAL',
                    beam=1e-80, wbeam=1e-60, pbeam=1e-80)
        for w, p in EXTRA.items():
            d.add_word(w, p, False)
        d.set_align_text(' '.join(t for t, _ in toks))
        wf = wave.open(wav, 'rb')
        d.start_utt(); d.process_raw(wf.readframes(wf.getnframes()), full_utt=True); d.end_utt()
    segs = [(s.word.split('(')[0], s.start_frame / 100, s.end_frame / 100) for s in d.seg()
            if s.word not in ('<sil>', '<s>', '</s>', '(NULL)', '[NOISE]')]
    times = [[None, None] for _ in raw]
    j = 0
    for t, ri in toks:
        while j < len(segs) and segs[j][0] != t:
            j += 1
        if j >= len(segs):
            raise SystemExit(f'chapter {n}: alignment lost at {t!r}')
        if times[ri][0] is None:
            times[ri][0] = segs[j][1]
        times[ri][1] = segs[j][2]
        j += 1
    return [[w.replace('’', "'"), round(a, 2), round(b, 2)] for w, (a, b) in zip(raw, times)]


def main():
    data = {n: align(n, t) for n, t in sorted(chapter_texts().items())}
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/align-neural-networks.py — word-level narration timings (seconds, per chapter clip).\n')
        f.write('export const WORDS = ' + json.dumps([data[n] for n in sorted(data)], ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('wrote', OUT, {n: len(v) for n, v in data.items()})


if __name__ == '__main__':
    main()
